def craft_warnings(plan: dict[str, Any]) -> list[str]:
    """对导演方案做审美层面的软检查：只提示，不阻断，也不改写任何内容。"""
    units = [u for u in plan.get("units") or [] if isinstance(u, dict)]
    warnings: list[str] = []
    if len(units) >= 3 and len({u.get("duration_seconds") for u in units}) == 1 and (plan.get("production_policy") or {}).get("shot_duration_mode") != "fixed15":
        warnings.append("所有镜头时长相同，节奏偏平，建议按内容密度调整时长")
    directions = [
        str(seg.get("camera_direction") or "").strip()
        for u in units
        for seg in (u.get("storyboard_json") or {}).get("segments", [])
        if isinstance(seg, dict)
    ]
    if len(directions) >= 4 and len(set(directions)) <= max(1, len(directions) // 4):
        warnings.append("镜头景别与运镜高度重复，建议增加景别变化与反应镜头")
    scales = "远景全景中景近景特写"
    for prev, cur in zip(units, units[1:]):
        p_scale, c_scale = str(prev.get("closing_shot_scale") or ""), str(cur.get("opening_shot_scale") or "")
        technique = str(cur.get("transition_technique") or "").strip()
        uid = cur.get("unit_id")
        if not technique:
            warnings.append(f"{uid}缺少转场手法，可能出现生硬切换")
        if p_scale and p_scale == c_scale and technique not in ("匹配剪辑", "正反打"):
            warnings.append(f"{uid}与上一镜景别相同（{c_scale}），有跳切风险，建议改变景别或使用匹配剪辑")
        if p_scale in scales and c_scale in scales and p_scale and c_scale:
            order = ["远景", "全景", "中景", "近景", "特写"]
            if p_scale in order and c_scale in order and abs(order.index(p_scale) - order.index(c_scale)) > 2:
                warnings.append(f"{uid}景别跨度过大（{p_scale}→{c_scale}），建议加过渡镜头")
    return warnings
